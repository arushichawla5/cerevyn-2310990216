"""Synthetic sample data and .npz loading.

The sample farm is SYNTHETIC (generated here with a fixed seed); it is not real
satellite imagery. Bands are derived from chosen NDVI targets so the expected
outcome is known in advance.
"""
from __future__ import annotations

import io
from pathlib import Path

import numpy as np

from .core import InputError

SIZE = 20
SEED = 42
KEYS = ("red1", "nir1", "valid1", "red2", "nir2", "valid2", "farm")
ORIGIN = "SYNTHETIC: generated by ndvi_monitor.data.make_sample(seed=42); not real imagery."


def _bands(ndvi, red):
    """NIR such that (nir-red)/(nir+red) == ndvi for the given red."""
    return red * (1 + ndvi) / (1 - ndvi)


def make_sample(seed: int = SEED) -> dict:
    rng = np.random.default_rng(seed)
    n = SIZE
    yy, xx = np.mgrid[0:n, 0:n]

    # Farm: a 16x16 field with its top-left corner cut off (non-rectangular).
    farm = (yy >= 2) & (yy < 18) & (xx >= 2) & (xx < 18)
    farm &= ~((yy < 6) & (xx < 6))

    red1 = rng.uniform(0.06, 0.10, (n, n))
    ndvi1 = np.clip(0.70 + rng.normal(0, 0.02, (n, n)), 0.5, 0.85)
    nir1 = _bands(ndvi1, red1)

    # Date 2: same field, a 6x6 patch (rows 8-13, cols 8-13) lost vegetation.
    red2 = red1 + rng.normal(0, 0.003, (n, n))
    ndvi2 = np.clip(0.69 + rng.normal(0, 0.02, (n, n)), 0.5, 0.85)
    patch = (yy >= 8) & (yy < 14) & (xx >= 8) & (xx < 14)
    ndvi2[patch] = np.clip(0.30 + rng.normal(0, 0.02, patch.sum()), 0.1, 0.5)
    nir2 = _bands(ndvi2, red2)

    # Different cloud masks per date (False = cloud / invalid).
    valid1 = np.ones((n, n), bool)
    valid1[3:7, 12:17] = False
    valid2 = np.ones((n, n), bool)
    valid2[14:18, 3:8] = False

    # A pixel whose both bands are zero on date 1 (zero denominator), on the farm.
    red1[10, 4] = 0.0
    nir1[10, 4] = 0.0

    return {
        "red1": red1, "nir1": nir1, "valid1": valid1,
        "red2": red2, "nir2": nir2, "valid2": valid2, "farm": farm,
    }


def save_npz(arrays: dict, path) -> None:
    np.savez_compressed(path, **{k: arrays[k] for k in KEYS}, origin=np.array(ORIGIN))


def to_arrays(npz) -> dict:
    """Validate a loaded npz (or dict) and return the arrays used by compare()."""
    missing = [k for k in KEYS if k not in npz]
    if missing:
        raise InputError(f"missing arrays: {', '.join(missing)}")
    out = {k: np.asarray(npz[k]) for k in KEYS}
    shapes = {v.shape for v in out.values()}
    if len(shapes) != 1 or len(next(iter(shapes))) != 2:
        raise InputError("all arrays must be 2-D with identical shapes")
    return out


def load_npz_bytes(raw: bytes) -> dict:
    try:
        with np.load(io.BytesIO(raw), allow_pickle=False) as npz:
            return to_arrays({k: npz[k] for k in npz.files})
    except InputError:
        raise
    except Exception as exc:  # corrupt / not an npz
        raise InputError(f"could not read .npz upload: {exc}") from exc


def load_sample() -> dict:
    path = Path(__file__).parent.parent / "sample_data" / "farm_two_dates.npz"
    if path.exists():
        return load_npz_bytes(path.read_bytes())
    return make_sample()
